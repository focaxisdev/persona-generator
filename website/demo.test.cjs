'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {createModel, REGISTRY, SOURCE_SHA} = require('./demo.js');
const model = createModel();
assert.equal(Object.keys(model.snapshot().targets).length, 10);
assert.ok(Object.values(model.snapshot().targets).every(x => x === 'unspecified'));
const malicious = '<img src=x onerror=alert(1)>\n keep this verbatim ';
const rawId = model.freeText(malicious);
assert.equal(model.snapshot().unknown_answers[0].text, malicious);
assert.equal(model.snapshot().unknown_answers[0].interpretation, 'unknown');
model.makePreview();
assert.throws(() => model.confirm(true), /檢視未知回答/);
model.keepUnknown(rawId);
model.makePreview(); model.confirm(true);
assert.ok(model.exportText().includes(malicious.replace('\n', '\\n')));
model.choice('bfas.politeness', 'low', 'plain wording', rawId);
assert.equal(model.isConfirmed, false);
assert.throws(() => model.exportText(), /匯出尚未開放/);
model.choice('bfas.politeness', 'high', 'courteous wording');
let snap = model.snapshot();
assert.equal(snap.conflicts.length, 1);
assert.deepEqual(snap.conflicts[0].candidates.map(c => c.target), ['low', 'high']);
assert.equal(snap.targets['bfas.politeness'], 'unspecified');
model.makePreview(); assert.throws(() => model.confirm(true), /解決/);
model.resolve('C1', 'middle');
assert.equal(model.snapshot().targets['bfas.politeness'], 'middle');
assert.equal(model.snapshot().conflicts[0].candidates.length, 2);
model.flag('Raw text may contradict a preference; reviewed manually.');
model.makePreview(); assert.throws(() => model.confirm(true), /解決/);
model.resolve('C2');
model.makePreview(); model.confirm(true);
const exported = model.exportText();
const payload = JSON.parse(exported.split('```json\n')[1].split('\n```')[0]);
assert.deepEqual(payload, model.snapshot());
assert.equal(payload.behavioral_evidence, 'not_run');
assert.equal(payload.demo_only, true);
assert.equal(payload.source_base_sha, SOURCE_SHA);
assert.equal(payload.goals.find(g => g.aspect === 'bfas.politeness').rule, REGISTRY.find(g => g.id === 'bfas.politeness').rules.middle);
assert.equal(payload.unknown_answers[0].interpretation, 'unknown');
model.invalidate(); assert.throws(() => model.exportText(), /匯出尚未開放/);
model.choice('bfas.politeness', 'low');
assert.equal(model.snapshot().conflicts.filter(c => c.status === 'unresolved').length, 1);
assert.equal(model.snapshot().conflicts.filter(c => c.status === 'resolved').length, 2);
assert.throws(() => model.freeText('x'.repeat(2001)), /2000/);
assert.throws(() => model.freeText('  '), /2000/);
assert.throws(() => model.choice('bfas.fake', 'high'), /面向與目標/);
const registry = fs.readFileSync(require('node:path').join(__dirname, '../persona-design-v0.2/construct-registry.md'), 'utf8');
for (const row of REGISTRY) for (const rule of Object.values(row.rules)) assert.ok(registry.includes(rule), 'Exact registry rule: ' + rule);
const code = fs.readFileSync(__dirname + '/demo.js', 'utf8');
assert.doesNotMatch(code, /innerHTML|outerHTML|insertAdjacentHTML|\bfetch\s*\(|XMLHttpRequest|WebSocket|localStorage|sessionStorage|document\.cookie|sendBeacon/);
console.log('Demo state checks passed: 10 unspecified targets, verbatim unknowns, exact rules, conflict preservation, explicit resolution, immutable preview export and invalidation, input bounds, no unsafe HTML or outbound APIs.');
